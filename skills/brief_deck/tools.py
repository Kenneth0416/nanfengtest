_DECK_WORDS = ("slide", "deck", "pptx", "ppt", "powerpoint", "presentation", "簡報", "简报", "投影片", "幻燈片", "幻灯片")
_THEME_WORDS = {"forest": "forest-cream", "green": "forest-cream", "charcoal": "charcoal-amber", "amber": "charcoal-amber",
                "dark": "charcoal-amber", "navy": "navy-gold", "gold": "navy-gold", "editorial": "editorial-cream",
                "cream": "editorial-cream", "white": "data-white", "data white": "data-white",
                "client": "forest-cream", "客戶": "forest-cream", "客户": "forest-cream", "research": "editorial-cream",
                "研究": "editorial-cream", "screen": "charcoal-amber", "投影": "charcoal-amber", "森林": "forest-cream",
                "深色": "charcoal-amber", "炭": "charcoal-amber", "深藍": "navy-gold", "深蓝": "navy-gold", "白": "data-white"}


def deck_request(text: str) -> tuple[str, str] | None:
    """(format, theme) when a sentence asks for slides, so the app can still build a deck without the Copilot.
    "a client update deck on the forest theme" -> ("board", "forest-cream"); "slides for the IC" -> ("ic", "data-white")."""
    t = text.lower()
    if not any(w in t for w in _DECK_WORDS):
        return None
    ic = bool(re.search(r"\bic\b|investment committee|投委會|投委会|投資委員會|投资委员会", t))
    theme = next((v for k, v in _THEME_WORDS.items() if k in t), "data-white" if ic else "navy-gold")
    return ("ic" if ic else "board", theme)


def deck_data(ctx, fmt: str = "board") -> dict:
    """Everything a deck states, from the library: the same summary, signals and footnotes as the
    markdown brief (generate_brief), plus the chart series."""
    st = ctx.store
    notes = Footnotes(st)
    items = st.brief_items()
    picked = bool(items)
    sigs = [_signal(i) for i in items] if picked else SignalEngine(st, ctx.config).for_role("team")
    talk = [s for s in sigs if is_tip(s)][:3]
    sigs = [s for s in sigs if not is_tip(s)][: 6]

    def ref(source_id):
        r = an.source_ref(st, source_id)
        return notes.ref(r["title"], r["url"], source_id)

    def series(market, metric):
        return [{"period": an.period_label(r["period"]), "value": r["value"], "lta": r["lta"],
                 "ref": ref(r["source_id"]), "flagged": r.get("status") == "flagged"}
                for r in an.series(st, market, metric)]

    def snap(market, metric):
        s = an.snapshot(st, market, metric)
        if not s:
            return None
        lta = next((r["lta"] for r in reversed(an.series(st, market, metric)) if r.get("lta")), None)
        return {"market": market, "metric": metric, "label": tx.METRICS[metric]["label"],
                "value": s["value"], "text": tx.fmt_value(metric, s["value"]), "period": an.period_label(s["period"]),
                "prev": s["prev_value"], "prev_period": an.period_label(s["prev_period"]) if s["prev_period"] else "",
                "change": s["change"], "lta": lta,
                "vs_lta_pct": round((s["value"] / lta - 1) * 100) if lta else None,
                "ref": ref(s["source_id"]), "flagged": s["status"] == "flagged", "warning": an.warning(s)}

    kpis = [k for k in (snap("London", "vacancy_pct"), snap("London", "take_up_msqft"),
                        snap("London", "investment_gbp_bn"), snap("London", "active_requirements_msqft")) if k]
    rate = st.q("SELECT * FROM macro WHERE indicator='bank_rate' ORDER BY date DESC LIMIT 1")
    macro = None
    if rate:
        macro = {"label": "Bank Rate", "value": rate[0]["value"], "text": f"{rate[0]['value']:.2f}%",
                 "as_of": rate[0]["date"],
                 "ref": notes.ref("Bank of England Bank Rate",
                                  "https://www.bankofengland.co.uk/boeapps/database/Bank-Rate.asp")}

    # Prime rents by submarket, latest period, with the quarter's move.
    latest = an.latest_period(st)
    rents = []
    for r in st.q("SELECT DISTINCT market FROM observations WHERE metric='prime_rent_psf'"):
        s = snap(r["market"], "prime_rent_psf")
        if s and s["period"] == an.period_label(latest):
            rents.append(s)
    rents.sort(key=lambda s: -s["value"])

    areas = [a for a in tx.TOP_MARKETS[1:]]
    invest = [s for s in (snap(a, "investment_gbp_bn") for a in areas) if s]
    yields = [s for s in (snap(a, "prime_yield_pct") for a in areas) if s]

    def card(s):
        return {"title": s.title, "detail": s.detail, "why": s.why, "tone": s.tone, "kind": s.kind,
                "markets": s.markets[:2], "flag": s.flag,
                "refs": "".join(notes.ref(e.text, e.url, e.source_id) for e in s.evidence)}

    # IC paper: evidence for the submarkets the person asking covers (their focus, else the big three).
    focus = st.focus(ctx.role) or focus_mod.defaults(ctx.config)
    ic_markets = focus["markets"] or list(tx.TOP_MARKETS[1:])
    evidence = []
    for m in ic_markets:
        row = {"market": m, "cells": []}
        for metric in IC_METRICS:
            market, _ = an.resolve_for_metric(st, m, metric)
            sn = snap(market, metric)
            row["cells"].append({"metric": metric, "label": tx.METRICS[metric]["label"],
                                 "text": (sn["text"] + (" (flagged)" if sn["flagged"] else "") + " " + sn["ref"]) if sn else "n/a",
                                 "change": chg_text(sn) if sn else ""})
        evidence.append(row)

    ours = I.for_brief(st, fmt)
    our_deals = [{"property": d["property"], "tenant": d.get("tenant") or "Tenant not recorded", "rent": d.get("rent") or "",
                  "term": d.get("term") or "", "rent_free": d.get("rent_free") or "", "date": d.get("date") or "",
                  "submarket": d.get("submarket") or "", "level": d.get("confidentiality", "internal"),
                  "ext": (d["ext"]["text"] if d.get("ext") and d["ext"].get("differs") else "")} for d in ours["ours"]]
    market_deals = [{**m, "ref": notes.ref(m["title"], m["url"], m["source_id"])} for m in I.market_deals(st)]
    flagged = [k["warning"] for k in kpis + rents + invest + yields if k["flagged"]]
    team = ctx.config.get("team", {})
    rules = st.watch_rules()
    who = sorted({i["added_by"] for i in items if i.get("added_by")})
    d = {
        "format": fmt, "evidence": evidence, "focus": {"markets": focus.get("markets") or []},
        "title": "IC paper: London office market" if fmt == "ic" else f"{team.get('name', 'Team')}: weekly brief",
        "date": f"{date.today():%d %b %Y}",
        "picked_by": (f"{len(sigs)} signals chosen by {', '.join(who)}" if picked
                      else build_deck.cover_line(fmt, f"{date.today():%d %b %Y}", kpis[0]["period"] if kpis else "")),
        "headline": team_summary(st, sigs),
        "kpis": kpis, "macro": macro,
        "vacancy": series("London", "vacancy_pct"), "take_up": series("London", "take_up_msqft"),
        "rents": rents, "investment": invest, "yields": yields,
        "signals": [card(s) for s in sigs], "talk": [card(s) for s in talk],
        "our_deals": our_deals, "market_deals": market_deals, "deals_filtered": ours["filtered"],
        "flagged": flagged, "footnotes": notes.markdown(),
        "caveat": "Figures restated from public research for this proof of concept (Knight Frank terms bar AI use "
                  "of their data); verify against the original before external use.",
    }
    d["stories"] = planner.stories(d, d["focus"], rules)  # what stands out this week, ranked, each with its reason
    return d




