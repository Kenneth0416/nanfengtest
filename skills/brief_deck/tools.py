def brief_deck_data(ctx, args):
    d = deck_data(ctx, args.get("format") or "board")
    k = ", ".join(f"{x['label']} {x['text']} ({x['period']})" for x in d["kpis"])
    charts = [c for c in build_deck.CHARTS if d.get(c)]
    stories = "\n".join(f"- {c['key']} (score {c['score']}): {c['reason']} → suggested {c['layout']}: \"{c['title']}\""
                        for c in d["stories"])
    return {"summary": f"{d['title']} · {d['date']} · {d['picked_by']}.\nHeadline: {' '.join(d['headline'])}\n"
                       f"KPIs: {k}.\nCharts with data: {', '.join(charts)}; tables: "
                       f"{', '.join(t for t in build_deck.TABLES if d.get(t))}.\n"
                       f"What stands out this week, ranked (you decide which deserve a slide, 1-4 content slides):\n{stories}\n"
                       f"{len(d['signals'])} signal cards, {len(d['talk'])} market-talk items, {len(d['our_deals'])} of our deals, "
                       f"{len(d['flagged'])} flagged figures, {len(d['footnotes'])} footnotes. "
                       f"Focus of the person asking: {', '.join(d['focus']['markets']) or 'whole market'}.",
            "data": d}


def brief_deck_guide(ctx, args):
    """The design pack's reference notes, for writing a spec (the agent cannot read files itself)."""
    topic = args.get("topic") or "storyline"
    path = GUIDES.get(topic)
    if not path:
        return {"summary": f"Unknown topic {topic!r}; one of {', '.join(GUIDES)}.", "data": {}}
    text = path.read_text()
    themes = {k: {"use_for": v["use_for"], "mood": v["mood"], "visual_density": v["visual_density"]}
              for k, v in build_deck.THEMES.items()}
    return {"summary": text if topic in ("storyline", "layouts", "style") else f"Example spec ({topic}):\n{text}",
            "data": {"topic": topic, "themes": themes, "layouts": build_deck.LAYOUTS,
                     "charts": build_deck.CHARTS, "tables": build_deck.TABLES, "heroes": build_deck.HEROES,
                     **({"spec": json.loads(text)} if path.suffix == ".json" else {})}}


def build_brief_pptx(ctx, args):
    """The deck, from the library only: the agent's `spec` (or the old `slides`) carries the words, never figures."""
    fmt = args.get("format") or "board"
    d = deck_data(ctx, fmt)
    theme = args.get("theme") or None
    spec = args.get("spec") or None
    storyline = "copilot" if spec else "rules"
    if spec is None:  # no model: the planner picks this week's stories (rule-picked, not a fixed template)
        spec = planner.plan_spec(d, theme, d.get("focus"), ctx.store.watch_rules())
        if args.get("slides"):
            spec = build_deck.merge_overrides(spec, args["slides"])
    spec = {k: v for k, v in spec.items() if k in ("theme", "slides")}
    folder = ctx.root / "data" / "exports"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{date.today():%Y-%m-%d}-team-brief-{fmt}.pptx"
    dd = {k: v for k, v in d.items() if k not in ("stories", "focus")}  # scores and focus are not figures a slide may quote
    try:
        built = build_deck.build(dd, str(path), spec, theme)
    except ValueError as e:
        # structured: which numbers were refused where, and the latest values a title may quote instead
        numbers = build_deck.refused_numbers({**spec, "theme": theme or spec.get("theme")}, dd)
        latest = {k["metric"]: k.get("text", "") for k in d.get("kpis") or [] if k.get("metric")}
        return {"summary": f"Not built: {e}. Rewrite that text with the figures as the data gives them, or without "
                           f"the number, and call again.", "data": {"error": str(e), "refused": [str(e)],
                                                                    "refused_numbers": numbers, "latest": latest,
                                                                    "slides_given": len(spec.get("slides") or [])}}
    spec = built["spec"]  # with the ids the build gave new slides
    report = check_deck.check(str(path), dd)
    slides = built["slides"]
    lines = "\n".join(f"{i + 1}. [{s['layout']}] {s['title']}" for i, s in enumerate(slides))
    problems = report["problems"]
    summary = (f"Deck saved: {len(slides)} slides, theme {built['theme']}, storyline "
               f"{'written by the Copilot' if storyline == 'copilot' else 'picked by rules from this week\'s data (no model)'}, "
               f"at {path}.\n{lines}")
    if problems:
        summary += "\nCheck found " + str(len(problems)) + " problem(s); fix the spec and build again:\n- " + \
                   "\n- ".join(problems)
    return {"summary": summary,
            "data": {"path": str(path), "theme": built["theme"], "slides": slides, "refused": [],
                     "problems": problems, "format": fmt, "storyline": storyline, "spec": spec,
                     "why": [s.get("why", "") for s in spec["slides"]]}}


