"""Team brief as an editable PowerPoint, 3-6 slides, on one of five house themes.

Two halves:
  deck_data(ctx, fmt)                      -> dict  every figure, chart series and footnote, read from the store
  scripts/build_deck.build(d, path, spec)  -> dict  python-pptx fills templates/<theme>.pptx (13 named layouts)

The design pack (templates, themes, layouts and the two scripts) was written for this project after a
feature study of Grok Build's bundled pptx templates (research/grok-template-features.md): the layout
language is learned from them, no template file or code was copied. Templates are generated by
templates/build_template.js (pptxgenjs) and only rebuilt when a theme changes; the PoC needs python-pptx only.

Three tools: brief_deck_data (read-only), brief_deck_guide (read-only: storyline, layouts, style, an example
spec) and build_brief_pptx (writes data/exports/...pptx). The Copilot writes the storyline as a spec:
theme, layouts, order, eyebrows, titles, so-what lines and notes. Charts, tables, KPI tiles and footnotes
are named by key and drawn from deck_data, and build_deck.check_text refuses any number in the agent's
text that the data does not hold. After the build, check_deck reports leftover text, overflow, overlaps
and stray numbers as `problems` so the Copilot can fix and rebuild. The Streamlit page and the CLI build
the default storyline without a model.
"""
